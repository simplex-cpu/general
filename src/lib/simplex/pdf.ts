import { jsPDF } from "jspdf";
import { slugify, todayISO, type ReelSection } from "./reel";

const INK = "#1A1A1D";
const PURPLE = "#4F6BFF";
const ACCENT = "#6C7BFF";
const GRAY = "#9B9BA1";

/** Load /brand/wordmark-light.svg as a data URL we can hand to jsPDF. */
async function loadLogoDataURL(): Promise<string | null> {
  try {
    const res = await fetch("/brand/wordmark-light.svg");
    if (!res.ok) return null;
    const blob = await res.blob();
    return await new Promise<string>((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = () => resolve(reader.result as string);
      reader.onerror = () => reject(new Error("logo read failed"));
      reader.readAsDataURL(blob);
    });
  } catch {
    return null;
  }
}

/** Generate a branded reel-script PDF and trigger download. */
export async function downloadReelPDF({
  topic,
  sections,
}: {
  topic?: string;
  sections: ReelSection[];
}): Promise<void> {
  const doc = new jsPDF({ unit: "mm", format: "a4", orientation: "portrait" });
  const PAGE_W = 210;
  const PAGE_H = 297;
  const M = 20;
  const CONTENT_W = PAGE_W - M * 2;

  const logoData = await loadLogoDataURL();

  const drawHeader = () => {
    if (logoData) {
      // logo ~30px tall == ~10mm
      doc.addImage(logoData, "PNG", M, M - 4, 22, 10, undefined, "FAST");
    } else {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(11);
      doc.setTextColor(INK);
      doc.text("RISEVOICE", M, M);
    }
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(GRAY);
    const date = new Date().toLocaleDateString("en-US", {
      year: "numeric",
      month: "short",
      day: "numeric",
    });
    doc.text(date, PAGE_W - M, M, { align: "right" });
  };

  const drawFooter = (pageNum: number) => {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(GRAY);
    doc.text("Generated by Risevoice Creators Hub", PAGE_W / 2, PAGE_H - 10, { align: "center" });
    doc.text(String(pageNum), PAGE_W - M, PAGE_H - 10, { align: "right" });
  };

  let pageNum = 1;
  drawHeader();

  // Title
  let y = M + 18;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.setTextColor(INK);
  const title = topic?.trim() || "Reel Script";
  const titleLines = doc.splitTextToSize(title, CONTENT_W);
  doc.text(titleLines, M, y);
  y += titleLines.length * 9 + 4;

  // Divider
  doc.setDrawColor(PURPLE);
  doc.setLineWidth(0.4);
  doc.line(M, y, M + 30, y);
  y += 10;

  const ensureSpace = (needed: number) => {
    if (y + needed > PAGE_H - 20) {
      drawFooter(pageNum);
      doc.addPage();
      pageNum += 1;
      drawHeader();
      y = M + 18;
    }
  };

  for (const section of sections) {
    ensureSpace(20);
    // Section label
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(PURPLE);
    const label = section.label.toUpperCase();
    // Manually space-letter the label
    const spaced = label.split("").join(" ");
    doc.text(spaced, M, y);
    y += 6;

    // Section content
    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);
    doc.setTextColor(INK);
    const lines = doc.splitTextToSize(section.content || "—", CONTENT_W);
    const lineHeight = 5.5; // ~1.5 line-height at 11pt
    for (const line of lines) {
      ensureSpace(lineHeight);
      doc.text(line, M, y);
      y += lineHeight;
    }
    y += 8; // gap between sections
  }

  drawFooter(pageNum);

  const filename = `risevoice-script-${slugify(topic || "script")}-${todayISO()}.pdf`;
  doc.save(filename);
}
